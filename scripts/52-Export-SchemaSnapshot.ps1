<#
.SYNOPSIS
  Step 52 - Write a reference DDL snapshot of the app database that Rayfin created (read-only).

.DESCRIPTION
  The app database is NOT created from SQL scripts: `rayfin up` creates and migrates it from the entity classes in
  apps\<app>\packages\data\src (D-24). This script records what Rayfin actually built, so reviewers can read the
  physical schema without a Fabric login and detect drift after an SDK upgrade.

  It reads sys.tables / sys.columns / key, index and foreign-key catalog views with YOUR Entra token and writes
  docs\schema\<app>-schema.sql (deterministic order, no data, no timestamps inside the DDL body except the header).
  Do NOT run the output against a Rayfin database - Rayfin owns its migrations. Commit the file when it changes.

.EXAMPLE
  .\scripts\52-Export-SchemaSnapshot.ps1 -App ars
  .\scripts\52-Export-SchemaSnapshot.ps1 -App isob      # run 31-Resolve-AppDatabase.ps1 -App isob first
#>
[CmdletBinding()]
param(
  [ValidateSet('ars', 'isob')][string]$App = 'ars',
  [string]$Environment = 'dev'
)

Import-Module (Join-Path $PSScriptRoot 'IonovaDeploy.psm1') -Force
Update-SessionPath
$cfg = Read-IonovaConfig $Environment
$appCfg = Get-AppConfig $cfg $App
if (-not $appCfg.PSObject.Properties['sql']) { throw "apps.$App.sql is not set. Run scripts\31-Resolve-AppDatabase.ps1 -App $App first." }
Assert-NoPlaceholders $appCfg.sql "apps.$App.sql" -IncludeGenerated
$schema = if ($appCfg.sql.schema) { $appCfg.sql.schema } else { 'dbo' }

Write-Step "Reading the catalog of $($appCfg.sql.database)"
$conn = Open-FabricSqlConnection $appCfg.sql.server $appCfg.sql.database $cfg.org.tenantId
try {
  $cols = Invoke-SqlQuery $conn @'
SELECT t.name AS tbl, c.column_id, c.name AS col, ty.name AS typ, c.max_length, c.precision, c.scale, c.is_nullable, c.is_identity,
       dc.definition AS dflt
FROM sys.tables t
JOIN sys.schemas s ON s.schema_id = t.schema_id
JOIN sys.columns c ON c.object_id = t.object_id
JOIN sys.types ty ON ty.user_type_id = c.user_type_id
LEFT JOIN sys.default_constraints dc ON dc.object_id = c.default_object_id
WHERE s.name = @s AND t.is_ms_shipped = 0
ORDER BY t.name, c.column_id
'@ @{ s = $schema }
  $idx = Invoke-SqlQuery $conn @'
SELECT t.name AS tbl, i.name AS idx, i.is_primary_key, i.is_unique, i.is_unique_constraint, i.type_desc, ic.key_ordinal, ic.is_descending_key, c.name AS col
FROM sys.tables t
JOIN sys.schemas s ON s.schema_id = t.schema_id
JOIN sys.indexes i ON i.object_id = t.object_id AND i.type > 0
JOIN sys.index_columns ic ON ic.object_id = i.object_id AND ic.index_id = i.index_id AND ic.is_included_column = 0
JOIN sys.columns c ON c.object_id = ic.object_id AND c.column_id = ic.column_id
WHERE s.name = @s AND t.is_ms_shipped = 0
ORDER BY t.name, i.name, ic.key_ordinal
'@ @{ s = $schema }
  $fks = Invoke-SqlQuery $conn @'
SELECT fk.name AS fk, tp.name AS tbl, cp.name AS col, tr.name AS reftbl, cr.name AS refcol, fk.delete_referential_action_desc AS ondelete, fkc.constraint_column_id
FROM sys.foreign_keys fk
JOIN sys.foreign_key_columns fkc ON fkc.constraint_object_id = fk.object_id
JOIN sys.tables tp ON tp.object_id = fkc.parent_object_id
JOIN sys.schemas s ON s.schema_id = tp.schema_id
JOIN sys.columns cp ON cp.object_id = fkc.parent_object_id AND cp.column_id = fkc.parent_column_id
JOIN sys.tables tr ON tr.object_id = fkc.referenced_object_id
JOIN sys.columns cr ON cr.object_id = fkc.referenced_object_id AND cr.column_id = fkc.referenced_column_id
WHERE s.name = @s
ORDER BY tp.name, fk.name, fkc.constraint_column_id
'@ @{ s = $schema }
} finally { $conn.Close() }

function Format-SqlType($r) {
  $t = $r.typ
  switch -Regex ($t) {
    '^(n?varchar|n?char|varbinary|binary)$' {
      if ($r.max_length -eq -1) { return "$t(MAX)" }
      $len = if ($t -like 'n*') { $r.max_length / 2 } else { $r.max_length }
      return "$t($len)"
    }
    '^(decimal|numeric)$' { return "$t($($r.precision),$($r.scale))" }
    '^(datetime2|datetimeoffset|time)$' { return "$t($($r.scale))" }
    default { return $t }
  }
}

$nl = "`n"
$sb = New-Object System.Text.StringBuilder
[void]$sb.Append("-- Reference snapshot of the '$App' app database schema as created by Rayfin (rayfin up).$nl")
[void]$sb.Append("-- Generated by scripts/52-Export-SchemaSnapshot.ps1 from environment '$Environment' on $((Get-Date).ToUniversalTime().ToString('yyyy-MM-dd')) UTC.$nl")
[void]$sb.Append("-- Source of truth: apps/$($appCfg.path -replace '^apps/', '')/packages/data/src (entities). Rayfin owns migrations:$nl")
[void]$sb.Append("-- DO NOT run this file against a Rayfin database. Use it to review the physical schema and detect drift.$nl")
$tables = @($cols.Rows | ForEach-Object { $_.tbl } | Sort-Object -Unique)
foreach ($t in $tables) {
  [void]$sb.Append("$nl" + "CREATE TABLE [$schema].[$t] ($nl")
  $lines = New-Object System.Collections.Generic.List[string]
  foreach ($r in @($cols.Rows | Where-Object { $_.tbl -eq $t })) {
    $line = "    [$($r.col)] $(Format-SqlType $r)"
    if ($r.is_identity) { $line += ' IDENTITY' }
    $line += if ($r.is_nullable) { ' NULL' } else { ' NOT NULL' }
    if ($r.dflt -isnot [DBNull] -and $r.dflt) { $line += " DEFAULT $($r.dflt)" }
    $lines.Add($line)
  }
  $tIdx = @($idx.Rows | Where-Object { $_.tbl -eq $t })
  foreach ($name in @($tIdx | Where-Object { $_.is_primary_key -or $_.is_unique_constraint } | ForEach-Object { $_.idx } | Select-Object -Unique)) {
    $ic = @($tIdx | Where-Object { $_.idx -eq $name } | Sort-Object key_ordinal)
    $kind = if ($ic[0].is_primary_key) { "PRIMARY KEY $($ic[0].type_desc)" } else { 'UNIQUE' }
    $lines.Add("    CONSTRAINT [$name] $kind ($((@($ic | ForEach-Object { "[$($_.col)]" })) -join ', '))")
  }
  [void]$sb.Append(($lines -join ",$nl") + "$nl);$nl")
  foreach ($name in @($tIdx | Where-Object { -not $_.is_primary_key -and -not $_.is_unique_constraint } | ForEach-Object { $_.idx } | Select-Object -Unique)) {
    $ic = @($tIdx | Where-Object { $_.idx -eq $name } | Sort-Object key_ordinal)
    $u = if ($ic[0].is_unique) { 'UNIQUE ' } else { '' }
    $keys = @($ic | ForEach-Object { "[$($_.col)]" + $(if ($_.is_descending_key) { ' DESC' } else { '' }) }) -join ', '
    [void]$sb.Append("CREATE $u$($ic[0].type_desc) INDEX [$name] ON [$schema].[$t] ($keys);$nl")
  }
}
$fkNames = @($fks.Rows | ForEach-Object { $_.fk } | Select-Object -Unique)
if ($fkNames.Count) { [void]$sb.Append("$nl-- Foreign keys$nl") }
foreach ($name in $fkNames) {
  $fc = @($fks.Rows | Where-Object { $_.fk -eq $name } | Sort-Object constraint_column_id)
  $del = if ($fc[0].ondelete -ne 'NO_ACTION') { " ON DELETE $($fc[0].ondelete -replace '_', ' ')" } else { '' }
  [void]$sb.Append("ALTER TABLE [$schema].[$($fc[0].tbl)] ADD CONSTRAINT [$name] FOREIGN KEY ($((@($fc | ForEach-Object { "[$($_.col)]" })) -join ', ')) REFERENCES [$schema].[$($fc[0].reftbl)] ($((@($fc | ForEach-Object { "[$($_.refcol)]" })) -join ', '))$del;$nl")
}

$dir = Join-Path (Get-RepoRoot) 'docs\schema'
if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
$file = Join-Path $dir "$App-schema.sql"
[IO.File]::WriteAllText($file, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Ok "$($tables.Count) tables, $(@($idx.Rows | ForEach-Object { "$($_.tbl).$($_.idx)" } | Select-Object -Unique).Count) indexes/keys, $($fkNames.Count) foreign keys -> $file"
Write-Host 'Commit docs\schema\ when it changes (for example after a Rayfin SDK upgrade or an entity change).'
